export function toolPath(tool, lang) {
  return lang === 'en' ? `/en/${tool.slug.en}/` : `/${tool.slug.vi}/`;
}

export function appPath(lang, params = '') {
  const q = [params, lang === 'en' ? 'lang=en' : ''].filter(Boolean).join('&');
  return `/app/${q ? `?${q}` : ''}`;
}

